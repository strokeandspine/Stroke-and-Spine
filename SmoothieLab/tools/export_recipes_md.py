#!/usr/bin/env python3
"""Write RECIPES.md: every recipe grouped by goal, with nutrition computed from ingredients.json.

Usage: python3 tools/export_recipes_md.py
"""
from pathlib import Path
from validate_recipes import load, nutrition

OUT = Path(__file__).resolve().parent.parent / "RECIPES.md"
SORT = {
    "proteinDensity": lambda n: -n["protein"] / n["kcal"], "proteinDesc": lambda n: -n["protein"],
    "kcalAsc": lambda n: n["kcal"], "kcalDesc": lambda n: -n["kcal"],
    "netCarbsAsc": lambda n: n["netCarbs"], "carbsDesc": lambda n: -n["carbs"],
}


def main():
    ingredients = {i["id"]: i for i in load("ingredients.json")}
    objectives = load("objectives.json")
    recipes = load("recipes.json")
    info = {r["id"]: nutrition(r, ingredients)[0] for r in recipes}
    titles = {o["id"]: o["title"] for o in objectives}

    md = ["# Smoothie Lab recipes", "",
          f"{len(recipes)} recipes. Nutrition is per glass, computed from `ingredients.json` "
          "(USDA FoodData Central for whole foods, typical label values for supplements). "
          "Generated by `tools/export_recipes_md.py` — edit the JSON, not this file.", "",
          "## By goal", ""]
    for o in objectives:
        md += [f"### {o['title']}", f"_{o['subtitle']}_", "",
               "| Recipe | kcal | Protein | Carbs | Fat | Fiber | Protein / 100 kcal |",
               "|---|---:|---:|---:|---:|---:|---:|"]
        members = [r for r in recipes if o["id"] in r["objectives"]]
        for r in sorted(members, key=lambda r: SORT[o["sort"]](info[r["id"]])):
            n = info[r["id"]]
            md.append(f"| [{r['name']}](#{r['id']}) | {n['kcal']:.0f} | {n['protein']:.0f} g | {n['carbs']:.0f} g "
                      f"| {n['fat']:.0f} g | {n['fiber']:.0f} g | {n['protein'] / n['kcal'] * 100:.1f} g |")
        md.append("")

    md += ["## Recipes", ""]
    for r in recipes:
        n = info[r["id"]]
        md += [f'<a id="{r["id"]}"></a>', f"### {r['name']}", f"*{r['tagline']}* — {r['flavor']}", "",
               f"**{n['kcal']:.0f} kcal** · {n['protein']:.0f} g protein · {n['carbs']:.0f} g carbs "
               f"({n['netCarbs']:.0f} g net) · {n['fat']:.0f} g fat · {n['fiber']:.0f} g fiber · "
               f"{n['sugar']:.0f} g sugars ({n['addedSugar']:.0f} g added)", "",
               "Goals: " + ", ".join(titles[o] for o in r["objectives"]), ""]
        for line in r["ingredients"]:
            ing = ingredients[line["id"]]
            tag = " *(supplement)*" if ing["kind"] == "supplement" else ""
            md.append(f"- {ing['name']}{tag}: {line['measure']} ({line['grams']:g} g)")
        md.append("")
        md += [f"{i}. {s}" for i, s in enumerate(r["steps"], 1)]
        md += ["", f"**Why it works:** {r['whyItWorks']}"]
        if r.get("timing"):
            md.append(f"\n**When:** {r['timing']}")
        if r.get("swaps"):
            md.append("\n**Swaps:** " + " ".join(r["swaps"]))
        md.append("")
    OUT.write_text("\n".join(md), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
